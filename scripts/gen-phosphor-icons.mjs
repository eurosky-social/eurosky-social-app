#!/usr/bin/env node
/**
 * Imports pinned Phosphor artwork into the upstream SVG icon pipeline and
 * generates the embed wrappers. App components and native fonts are generated
 * separately by `pnpm icons:generate`. Compatibility names keep fork and
 * upstream call sites working without restoring restricted upstream artwork.
 */

import fs from 'node:fs'
import path from 'node:path'
import {createRequire} from 'node:module'
import {fileURLToPath} from 'node:url'
import prettier from 'prettier'
import {optimize} from 'svgo'

import {normalizeExportName} from './icons/lib.mts'
import svgoConfig from '../svgo.config.mjs'

const require = createRequire(import.meta.url)
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const MANIFEST_PATH = path.join(ROOT, 'scripts/phosphor-icons.json')
const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'))
const coreRoot = path.resolve(
  path.dirname(require.resolve('@phosphor-icons/core')),
  '..',
)
const corePackage = JSON.parse(
  fs.readFileSync(path.join(coreRoot, 'package.json'), 'utf8'),
)
if (corePackage.version !== manifest.version) {
  throw new Error(
    `Phosphor manifest expects ${manifest.version}, installed ${corePackage.version}`,
  )
}
const drifts = []
const importedSources = new Set()

function readIcon({icon, weight}) {
  const suffix = weight === 'regular' ? '' : `-${weight}`
  const source = path.join(coreRoot, 'assets', weight, `${icon}${suffix}.svg`)
  const svg = fs.readFileSync(source, 'utf8')
  const paths = [...svg.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)].map(
    match => match[1],
  )
  if (!paths.length) {
    throw new Error(`No paths found in ${path.relative(ROOT, source)}`)
  }
  return paths
}

function generatedHeader() {
  return `/**
 * Code generated by scripts/gen-phosphor-icons.mjs. DO NOT EDIT.
 * Phosphor Icons ${manifest.version}, MIT License. See NOTICE.md.
 */\n`
}

function importAppIcon(entry) {
  const name = normalizeExportName(
    {
      Bot_Stroke: 'Bot_Stroke2_Corner0_Rounded',
      Bot_Filled: 'Bot_Filled_Corner0_Rounded',
    }[entry.name] ?? entry.name,
  )
  const lane = name.includes('_') ? 'ui' : 'brands'
  const size = name.split('_').includes('Large') ? 64 : 24
  const paths = readIcon(entry)
    .map(d => `<path d="${d}"/>`)
    .join('')
  const rotation = name.startsWith('AspectRatio34_')
    ? ' rotate(90 128 128)'
    : ''
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" fill="currentColor" fill-rule="evenodd"><g transform="scale(${size / 256})${rotation}">${paths}</g></svg>`
  const relativePath = `assets/icons/${lane}/${name}.svg`
  importedSources.add(relativePath)
  // Stabilize optimization before comparison with the SVG codegen's own pass.
  let content = svg
  for (let pass = 0; pass < 10; pass++) {
    const next = optimize(content, {...svgoConfig, path: relativePath}).data
    if (next === content) break
    content = next
  }
  const output = path.join(ROOT, relativePath)
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : null
  if (current === content) return
  if (CHECK) {
    drifts.push(relativePath)
  } else {
    fs.mkdirSync(path.dirname(output), {recursive: true})
    fs.writeFileSync(output, content)
    console.log(`imported   ${relativePath}`)
  }
}

function generateEmbedIcons() {
  const resolved = manifest.embedIcons.map(entry => ({
    ...entry,
    paths: readIcon(entry),
  }))
  const pathConstants = resolved
    .map(entry => `const ${entry.name}Paths = ${JSON.stringify(entry.paths)}`)
    .join('\n')
  const exports = resolved
    .map(
      entry =>
        `export const ${entry.name} = (props: IconProps) => (\n  <PhosphorIcon {...props} paths={${entry.name}Paths} />\n)`,
    )
    .join('\n\n')

  return `${generatedHeader()}\nimport {h} from 'preact'\n\ntype IconProps = {\n  size?: number\n  className?: string\n}\n\nfunction PhosphorIcon({\n  paths,\n  size = 24,\n  className,\n}: IconProps & {paths: string[]}) {\n  return (\n    <svg\n      aria-hidden="true"\n      className={className}\n      width={size}\n      height={size}\n      xmlns="http://www.w3.org/2000/svg"\n      fill="currentColor"\n      viewBox="0 0 256 256">\n      {paths.map(path => (\n        <path key={path} d={path} />\n      ))}\n    </svg>\n  )\n}\n\n${pathConstants}\n\n${exports}\n`
}

async function emit(relativePath, content) {
  const output = path.join(ROOT, relativePath)
  const prettierConfig = (await prettier.resolveConfig(output)) || {}
  const formatted = await prettier.format(content, {
    ...prettierConfig,
    filepath: output,
  })
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : null
  if (current === formatted) return
  if (CHECK) {
    drifts.push(relativePath)
    return
  }
  fs.mkdirSync(path.dirname(output), {recursive: true})
  fs.writeFileSync(output, formatted)
  console.log(`generated  ${relativePath}`)
}

const entries = new Map(
  Object.values(manifest.icons)
    .flat()
    .map(entry => [normalizeExportName(entry.name), entry]),
)
const upstreamIcons = JSON.parse(
  fs.readFileSync(
    path.join(ROOT, 'scripts/phosphor-upstream-icons.json'),
    'utf8',
  ),
)
for (const [name, icon] of Object.entries(upstreamIcons)) {
  if (!entries.has(name)) {
    entries.set(name, {
      name,
      icon,
      weight: name.includes('Filled') ? 'fill' : 'regular',
    })
  }
}
for (const entry of entries.values()) importAppIcon(entry)

/* A sync must not silently put restricted upstream artwork back in the fonts. */
for (const lane of ['ui', 'brands']) {
  for (const file of fs.readdirSync(path.join(ROOT, 'assets/icons', lane))) {
    if (!file.endsWith('.svg')) continue
    if (
      lane === 'brands' &&
      ['AppleLogo.svg', 'AndroidLogo.svg'].includes(file)
    )
      continue
    const relativePath = `assets/icons/${lane}/${file}`
    if (!importedSources.has(relativePath)) {
      throw new Error(
        `${relativePath}: unreviewed artwork. Map this export to Phosphor and replace its SVG before rebuilding fonts; do not restore restricted upstream assets.`,
      )
    }
  }
}
await emit('bskyembed/src/icons/Phosphor.tsx', generateEmbedIcons())

if (CHECK) {
  if (drifts.length) {
    console.error(
      `Phosphor icons are out of sync:\n  ${drifts.join('\n  ')}\n\nRun: pnpm icons:import-phosphor`,
    )
    process.exit(1)
  }
  console.log('Phosphor icons in sync')
}
