#!/usr/bin/env node
/**
 * Generates the app and embed icon wrappers from pinned Phosphor SVG assets.
 *
 * The manifest intentionally keeps the app's existing export names so the icon
 * migration does not require unrelated call-site churn. New icons should use
 * canonical Phosphor names. Run with --check in CI to detect generated drift.
 */

import fs from 'node:fs'
import path from 'node:path'
import {createRequire} from 'node:module'
import {fileURLToPath} from 'node:url'
import prettier from 'prettier'

const require = createRequire(import.meta.url)
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const MANIFEST_PATH = path.join(ROOT, 'scripts/phosphor-icons.json')
const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'))
const coreRoot = path.resolve(
  path.dirname(require.resolve('@phosphor-icons/core')),
  '..',
)
const corePackage = JSON.parse(
  fs.readFileSync(path.join(coreRoot, 'package.json'), 'utf8'),
)
if (corePackage.version !== manifest.version) {
  throw new Error(
    `Phosphor manifest expects ${manifest.version}, installed ${corePackage.version}`,
  )
}
const drifts = []

function readIcon({icon, weight}) {
  const suffix = weight === 'regular' ? '' : `-${weight}`
  const source = path.join(coreRoot, 'assets', weight, `${icon}${suffix}.svg`)
  const svg = fs.readFileSync(source, 'utf8')
  const paths = [...svg.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)].map(
    match => match[1],
  )
  if (!paths.length) {
    throw new Error(`No paths found in ${path.relative(ROOT, source)}`)
  }
  return paths
}

function generatedHeader() {
  return `/**
 * Code generated by scripts/gen-phosphor-icons.mjs. DO NOT EDIT.
 * Phosphor Icons ${manifest.version}, MIT License. See NOTICE.md.
 */\n`
}

function generateAppIcon(entries) {
  const resolved = entries.map(entry => ({...entry, paths: readIcon(entry)}))
  const needsMultiPath = resolved.some(entry => entry.paths.length > 1)
  const imports = needsMultiPath
    ? "import {createMultiPathSVG, createSinglePathSVG} from './TEMPLATE'"
    : "import {createSinglePathSVG} from './TEMPLATE'"
  const exports = resolved
    .map(entry => {
      const source = `${entry.icon} (${entry.weight})`
      if (entry.paths.length === 1) {
        return `// Phosphor: ${source}\nexport const ${entry.name} = createSinglePathSVG({\n  viewBox: '0 0 256 256',\n  path: '${entry.paths[0]}',\n})`
      }
      return `// Phosphor: ${source}\nexport const ${entry.name} = createMultiPathSVG({\n  viewBox: '0 0 256 256',\n  paths: ${JSON.stringify(entry.paths)},\n})`
    })
    .join('\n\n')
  return `${generatedHeader()}\n${imports}\n\n${exports}\n`
}

function generateEmbedIcons() {
  const resolved = manifest.embedIcons.map(entry => ({
    ...entry,
    paths: readIcon(entry),
  }))
  const pathConstants = resolved
    .map(entry => `const ${entry.name}Paths = ${JSON.stringify(entry.paths)}`)
    .join('\n')
  const exports = resolved
    .map(
      entry =>
        `export const ${entry.name} = (props: IconProps) => (\n  <PhosphorIcon {...props} paths={${entry.name}Paths} />\n)`,
    )
    .join('\n\n')

  return `${generatedHeader()}\nimport {h} from 'preact'\n\ntype IconProps = {\n  size?: number\n  className?: string\n}\n\nfunction PhosphorIcon({\n  paths,\n  size = 24,\n  className,\n}: IconProps & {paths: string[]}) {\n  return (\n    <svg\n      aria-hidden="true"\n      className={className}\n      width={size}\n      height={size}\n      xmlns="http://www.w3.org/2000/svg"\n      fill="currentColor"\n      viewBox="0 0 256 256">\n      {paths.map(path => (\n        <path key={path} d={path} />\n      ))}\n    </svg>\n  )\n}\n\n${pathConstants}\n\n${exports}\n`
}

async function emit(relativePath, content) {
  const output = path.join(ROOT, relativePath)
  const prettierConfig = (await prettier.resolveConfig(output)) || {}
  const formatted = await prettier.format(content, {
    ...prettierConfig,
    filepath: output,
  })
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : null
  if (current === formatted) return
  if (CHECK) {
    drifts.push(relativePath)
    return
  }
  fs.mkdirSync(path.dirname(output), {recursive: true})
  fs.writeFileSync(output, formatted)
  console.log(`generated  ${relativePath}`)
}

const expectedAppFiles = new Set(
  Object.keys(manifest.icons).map(file => `${file}.tsx`),
)
const appIconDir = path.join(ROOT, 'src/components/icons')
for (const file of fs.readdirSync(appIconDir)) {
  if (!file.endsWith('.tsx') || expectedAppFiles.has(file)) continue
  const absolutePath = path.join(appIconDir, file)
  const content = fs.readFileSync(absolutePath, 'utf8')
  if (!content.includes('Code generated by scripts/gen-phosphor-icons.mjs')) {
    continue
  }
  if (CHECK) {
    drifts.push(`src/components/icons/${file} (stale)`)
  } else {
    fs.rmSync(absolutePath)
    console.log(`removed    src/components/icons/${file}`)
  }
}

for (const [file, entries] of Object.entries(manifest.icons)) {
  await emit(`src/components/icons/${file}.tsx`, generateAppIcon(entries))
}
await emit('bskyembed/src/icons/Phosphor.tsx', generateEmbedIcons())

if (CHECK) {
  if (drifts.length) {
    console.error(
      `Phosphor icons are out of sync:\n  ${drifts.join('\n  ')}\n\nRun: pnpm icons:generate`,
    )
    process.exit(1)
  }
  console.log('Phosphor icons in sync')
}
