#!/usr/bin/env node
/**
 * Imports pinned Lucide outlines and Filled Lucide silhouettes into the shared
 * SVG/component/font pipeline. Compatibility export names remain unchanged.
 */
import fs from 'node:fs/promises'
import {createRequire} from 'node:module'
import path from 'node:path'
import {fileURLToPath} from 'node:url'

import prettier from 'prettier'

import {normalizeExportName} from './icons/lib.mts'
import {iconSvg} from './icons/lucide.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const require = createRequire(import.meta.url)
const manifest = JSON.parse(
  await fs.readFile(path.join(ROOT, 'scripts/lucide-icons.json'), 'utf8'),
)
const drifts = []
const importedSources = new Set()

for (const [pkg, version] of Object.entries(manifest.packages)) {
  const installed = JSON.parse(
    await fs.readFile(require.resolve(`${pkg}/package.json`), 'utf8'),
  )
  if (installed.version !== version) {
    throw new Error(
      `Lucide manifest expects ${pkg} ${version}, installed ${installed.version}`,
    )
  }
}

async function emit(relativePath, content, format = false) {
  const output = path.join(ROOT, relativePath)
  if (format) {
    content = await prettier.format(content, {
      ...(await prettier.resolveConfig(output)),
      filepath: output,
    })
  }
  const current = await fs.readFile(output, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error
    return null
  })
  if (current === content) return
  if (CHECK) {
    drifts.push(relativePath)
  } else {
    await fs.mkdir(path.dirname(output), {recursive: true})
    await fs.writeFile(output, content)
    console.log(`imported   ${relativePath}`)
  }
}

for (const [exportName, entry] of Object.entries(manifest.icons)) {
  const name = normalizeExportName(exportName)
  if (name !== exportName) throw new Error(`Use normalized export name ${name}`)
  const lane = name.includes('_') ? 'ui' : 'brands'
  const size =
    name.split('_').includes('Large') || name.endsWith('Large') ? 64 : 24
  const relativePath = `assets/icons/${lane}/${name}.svg`
  importedSources.add(relativePath)
  await emit(relativePath, await iconSvg(entry, ROOT, {size}))
}

/* An upstream sync must never silently restore restricted or unmapped artwork. */
for (const lane of ['ui', 'brands']) {
  for (const file of await fs.readdir(path.join(ROOT, 'assets/icons', lane))) {
    if (!file.endsWith('.svg')) continue
    if (
      lane === 'brands' &&
      ['AppleLogo.svg', 'AndroidLogo.svg'].includes(file)
    )
      continue
    const relativePath = `assets/icons/${lane}/${file}`
    if (!importedSources.has(relativePath)) {
      throw new Error(
        `${relativePath}: unreviewed artwork. Map this export in scripts/lucide-icons.json before rebuilding fonts; do not restore restricted upstream assets.`,
      )
    }
  }
}

const embedConstants = []
const embedExports = []
for (const entry of manifest.embedIcons) {
  const svg = await iconSvg(entry, ROOT)
  const paths = [...svg.matchAll(/<path\b([^>]+)>/g)].map(([, attributes]) => ({
    d: /\bd="([^"]+)"/.exec(attributes)[1],
    fill: /\bfill="([^"]+)"/.exec(attributes)?.[1] ?? 'currentColor',
  }))
  embedConstants.push(`const ${entry.name}Paths = ${JSON.stringify(paths)}`)
  embedExports.push(
    `export const ${entry.name} = (props: IconProps) => <LucideIcon defaultSize={${entry.size ?? 24}} defaultHeight={${entry.height ?? entry.size ?? 24}} ${entry.fill ? `fill="${entry.fill}" ` : ''}{...props} paths={${entry.name}Paths} />`,
  )
}
await emit(
  'bskyembed/src/icons/Lucide.tsx',
  `/**
 * Code generated by scripts/gen-lucide-icons.mjs. DO NOT EDIT.
 * Lucide and Filled Lucide. ISC/MIT licenses. See NOTICE.md.
 */
import {h} from 'preact'

type IconProps = {
  size?: number
  width?: number
  height?: number
  fill?: string
  className?: string
}

function LucideIcon({
  paths,
  defaultSize,
  defaultHeight,
  size,
  width,
  height,
  fill = 'currentColor',
  className,
}: IconProps & {paths: {d: string; fill: string}[]; defaultSize: number; defaultHeight: number}) {
  return (
    <svg aria-hidden="true" className={className} width={width ?? size ?? defaultSize} height={height ?? size ?? defaultHeight} xmlns="http://www.w3.org/2000/svg" fill={fill} fillRule="evenodd" viewBox="0 0 24 24">
      {paths.map(path => <path key={path.d} d={path.d} fill={path.fill === 'currentColor' ? fill : path.fill} />)}
    </svg>
  )
}

${embedConstants.join('\n')}

${embedExports.join('\n\n')}
`,
  true,
)

const ogChat = await iconSvg(
  {icon: 'message-circle-more', variant: 'outline'},
  ROOT,
)
const ogPerson = await iconSvg({icon: 'user', variant: 'filled'}, ROOT)
const ogPath = svg => /<path\b[^>]*\bd="([^"]+)"/.exec(svg)[1]
await emit(
  'bskyogcard/src/components/Lucide.tsx',
  `/**
 * Code generated by scripts/gen-lucide-icons.mjs. DO NOT EDIT.
 * Lucide and Filled Lucide. ISC/MIT licenses. See NOTICE.md.
 */
export function ChatIcon(props: React.SVGProps<SVGSVGElement>) {
  return <svg width="32" height="32" viewBox="0 0 24 24" fill="white" fillRule="evenodd" {...props}><path d=${JSON.stringify(ogPath(ogChat))} /></svg>
}

export function PersonIcon(props: React.SVGProps<SVGSVGElement>) {
  return <svg viewBox="0 0 24 24" fill="white" fillRule="evenodd" {...props}><path d=${JSON.stringify(ogPath(ogPerson))} /></svg>
}
`,
  true,
)

if (CHECK && drifts.length) {
  console.error(
    `Lucide icons are out of sync:\n  ${drifts.join('\n  ')}\n\nRun: pnpm icons:import-lucide`,
  )
  process.exitCode = 1
} else {
  console.log(
    `Lucide icons ${CHECK ? 'in sync' : 'imported'} (${importedSources.size} app, ${manifest.embedIcons.length} embed)`,
  )
}
